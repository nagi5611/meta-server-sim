#!/usr/bin/env bash
# 本番 meta.mmh-virtual.jp: fail2ban 導入（root で実行。リポジトリは git pull 済み想定）
set -euo pipefail

REPO="${METASIM_INSTALL_DIR:-/home/nagi/sim-server/meta-server-sim}"
JAIL_SRC="${REPO}/scripts/security/fail2ban-jail.d-metasim-production.conf"
JAIL_DEST="/etc/fail2ban/jail.d/metasim-production.conf"
IGNOREIP_FILE="/etc/mmh-virtual/fail2ban-ignoreip.conf"
IGNOREIP_EXAMPLE="${REPO}/scripts/security/fail2ban-ignoreip.conf.example"
ENABLE_NGINX_JAILS="${METASIM_FAIL2BAN_NGINX:-auto}"

require_root() {
  if [[ "${EUID:-$(id -u)}" -ne 0 ]]; then
    echo "install-fail2ban: run as root (sudo -i or direct root shell)." >&2
    exit 1
  fi
}

build_ignoreip() {
  local base="127.0.0.1/8 ::1"
  if [[ -f "$IGNOREIP_FILE" ]]; then
    local extra=""
    while IFS= read -r line || [[ -n "$line" ]]; do
      line="${line%%#*}"
      line="$(echo "$line" | tr -d '[:space:]')"
      [[ -z "$line" ]] && continue
      extra="${extra} ${line}"
    done <"$IGNOREIP_FILE"
    base="${base}${extra}"
  fi
  printf '%s\n' "$base"
}

install_packages() {
  export DEBIAN_FRONTEND=noninteractive
  apt-get update -qq
  apt-get install -y -qq fail2ban
}

install_configs() {
  if [[ ! -f "$JAIL_SRC" ]]; then
    echo "install-fail2ban: missing ${JAIL_SRC} — git pull meta-server-sim on this host." >&2
    exit 1
  fi

  mkdir -p /etc/mmh-virtual
  if [[ ! -f "$IGNOREIP_FILE" ]] && [[ -f "$IGNOREIP_EXAMPLE" ]]; then
    install -m 0640 -o root -g root "$IGNOREIP_EXAMPLE" "$IGNOREIP_FILE"
    echo "install-fail2ban: created ${IGNOREIP_FILE} — add owner static IPs before relying on ignoreip."
  fi

  local ignoreip
  ignoreip="$(build_ignoreip)"

  install -m 0644 "$JAIL_SRC" "$JAIL_DEST"

  # Prepend [DEFAULT] ignoreip without clobbering the shipped file on upgrade — use drop-in.
  local dropin="/etc/fail2ban/jail.d/metasim-production-ignoreip.local"
  cat >"$dropin" <<EOF
# Generated by install-fail2ban-meta-production.sh — do not edit by hand; re-run installer.
[DEFAULT]
ignoreip = ${ignoreip}
EOF
  chmod 0644 "$dropin"
}

nginx_jails_decision() {
  local enable="$ENABLE_NGINX_JAILS"
  local nginx_src="${REPO}/scripts/security/fail2ban-jail.d-metasim-nginx.conf"
  local nginx_dest="/etc/fail2ban/jail.d/metasim-nginx.conf"

  if [[ "$enable" == "auto" ]]; then
    if command -v nginx >/dev/null 2>&1 && [[ -d /var/log/nginx ]]; then
      enable="1"
    else
      enable="0"
    fi
  fi

  if [[ "$enable" == "1" || "$enable" == "true" || "$enable" == "yes" ]]; then
    if [[ ! -f "$nginx_src" ]]; then
      echo "install-fail2ban: missing ${nginx_src}" >&2
      exit 1
    fi
    install -m 0644 "$nginx_src" "$nginx_dest"
    echo "install-fail2ban: nginx jails installed -> ${nginx_dest}"
  else
    rm -f "$nginx_dest"
    echo "install-fail2ban: nginx jails skipped (METASIM_FAIL2BAN_NGINX=${ENABLE_NGINX_JAILS})."
  fi
}

validate_and_start() {
  if ! fail2ban-client -d >/dev/null 2>&1; then
    echo "install-fail2ban: fail2ban-client -d failed — check jail syntax." >&2
    exit 1
  fi
  systemctl enable fail2ban
  systemctl restart fail2ban
  sleep 2
  fail2ban-client status
  fail2ban-client status sshd || echo "install-fail2ban: sshd jail not listed yet (check logs: journalctl -u fail2ban)."
}

main() {
  require_root
  install_packages
  install_configs
  nginx_jails_decision
  validate_and_start
  echo "install-fail2ban: done. Docs: docs/security/fail2ban-production.md"
}

main "$@"
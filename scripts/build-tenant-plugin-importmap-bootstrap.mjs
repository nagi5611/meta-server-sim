// scripts/build-tenant-plugin-importmap-bootstrap.mjs — bootstrap を lib/tenant-esm-deps と同期生成
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { TENANT_ESM_DEPS_MOUNT, buildTenantEsmImportMapImports } from '../lib/tenant-esm-deps.js';
import { parseTenantIdFromPathname } from '../lib/tenant-entry-path.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outPath = path.join(ROOT, 'public', 'js', 'tenant-plugin-importmap-bootstrap.js');

const generated = `// AUTO-GENERATED by scripts/build-tenant-plugin-importmap-bootstrap.mjs
// import map 仕様: lib/tenant-esm-deps.js buildTenantEsmImportMapImports
(function tenantPluginImportmapBootstrap() {
const TENANT_ESM_DEPS_MOUNT = ${JSON.stringify(TENANT_ESM_DEPS_MOUNT)};
${parseTenantIdFromPathname.toString()}
${buildTenantEsmImportMapImports.toString()}
    const tenantId = parseTenantIdFromPathname(window.location.pathname);
    if (!tenantId) return;
    if (document.getElementById('tenant-plugin-importmap-bootstrap')) return;
    const imports = buildTenantEsmImportMapImports(tenantId);
    const script = document.createElement('script');
    script.type = 'importmap';
    script.id = 'tenant-plugin-importmap-bootstrap';
    script.textContent = JSON.stringify({ imports });
    document.head.appendChild(script);
})();
`;

fs.writeFileSync(outPath, generated, 'utf8');
console.log(`[build] wrote ${path.relative(ROOT, outPath)}`);
